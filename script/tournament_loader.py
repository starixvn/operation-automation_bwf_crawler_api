"""
Tournament data loader module

This module handles loading and processing tournament files generated by scrapers.
"""

import os
import json
from collections import defaultdict
from typing import Dict, List, Tuple

from schema import TournamentData


def load_html_file(file_path: str, tournament_name: str, data_key: str, log_label: str, logger=None) -> Tuple[str, int]:
    """
    Load HTML file and return content with size
    
    Args:
        file_path: Path to the HTML file
        tournament_name: Name of the tournament
        data_key: Key to store in data dict (e.g., 'today_html')
        log_label: Label for logging (e.g., 'today schedule')
        logger: Optional logger instance
        
    Returns:
        Tuple of (html_content, file_size)
    """
    with open(file_path, 'r', encoding='utf-8') as f:
        html_content = f.read()
        file_size = len(html_content)
        if logger:
            logger.info(f"  {tournament_name}: {log_label} ({file_size:,} bytes)")
        return html_content, file_size


def load_round_info(file_path: str, tournament_name: str, logger=None) -> Dict[str, str]:
    """
    Load round_info.json and return tournament metadata
    
    Args:
        file_path: Path to the round_info.json file
        tournament_name: Name of the tournament
        logger: Optional logger instance
        
    Returns:
        Dictionary containing tournament_url, league_id, league_name, max_round
    """
    with open(file_path, 'r', encoding='utf-8') as f:
        json_data = json.load(f)
        if logger:
            logger.info(f"  {tournament_name}: max_round={json_data.get('max_round')}")
        return {
            'tournament_url': json_data.get('tournament_url', ''),
            'league_id': json_data.get('league_id', ''),
            'league_name': json_data.get('league_name', ''),
            'max_round': json_data.get('max_round')
        }


def load_tournament_files(folder: str, logger=None) -> Dict[str, Dict]:
    """
    Load all tournament files from folder and organize by tournament name
    
    Args:
        folder: Directory containing tournament files
        logger: Optional logger instance
        
    Returns:
        Dictionary mapping tournament_name to tournament data:
        {
            tournament_name: {
                today_html: str,
                tomorrow_html: str,
                tournament_url: str,
                league_id: str,
                league_name: str,
                max_round: str
            }
        }
    """
    tournaments_data = defaultdict(dict)
    
    # File type handlers configuration
    file_handlers = {
        '_today.html': ('today_html', 'today schedule'),
        '_tomorrow.html': ('tomorrow_html', 'tomorrow schedule'),
    }
    
    for filename in os.listdir(folder):
        file_path = os.path.join(folder, filename)
        
        # Handle HTML files
        for suffix, (data_key, log_label) in file_handlers.items():
            if filename.endswith(suffix):
                tournament_name = filename.replace(suffix, '')
                html_content, _ = load_html_file(file_path, tournament_name, data_key, log_label, logger)
                tournaments_data[tournament_name][data_key] = html_content
                break
        
        # Handle round_info.json
        if filename.endswith('_round_info.json'):
            tournament_name = filename.replace('_round_info.json', '')
            metadata = load_round_info(file_path, tournament_name, logger)
            tournaments_data[tournament_name].update(metadata)
    
    return tournaments_data


def build_tournament_list(tournaments_data: Dict[str, Dict], logger=None) -> List[TournamentData]:
    """
    Build list of TournamentData from tournaments_data dict
    
    Args:
        tournaments_data: Dictionary mapping tournament_name to tournament data
        logger: Optional logger instance
        
    Returns:
        List of TournamentData objects
    """
    tournaments = []
    
    for tournament_name, data in tournaments_data.items():
        has_today = 'today_html' in data
        has_tomorrow = 'tomorrow_html' in data
        
        if logger:
            logger.info(
                f"Tournament {tournament_name} ({data.get('league_name', 'N/A')}, "
                f"ID: {data.get('league_id', 'N/A')}): "
                f"today={has_today}, tomorrow={has_tomorrow}, max_round={data.get('max_round', 'N/A')}"
            )
        
        tournaments.append(TournamentData(
            tournament_url=data.get('tournament_url', ''),
            league_id=data.get('league_id', ''),
            league_name=data.get('league_name', ''),
            max_round=data.get('max_round'),
            today_html=data.get('today_html'),
            tomorrow_html=data.get('tomorrow_html')
        ))
    
    return tournaments

